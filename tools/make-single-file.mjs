// Inlines meesho-sorter/{style.css,js/*,vendor/*} into ONE standalone index.html (written to the
// project root, which `npm run build` then copies to dist/index.html).
//
//   node tools/make-single-file.mjs
//
// Source of truth stays in meesho-sorter/. No bundler or transpiler is involved: files are
// concatenated verbatim into <style>/<script> tags.
import fs from "node:fs";
import path from "node:path";

const dir = "meesho-sorter";
let html = fs.readFileSync(path.join(dir, "index.html"), "utf8");
const read = (p) => fs.readFileSync(path.join(dir, p), "utf8");
// Raw control characters inside JS string literals (e.g. "PK\x03\x04" in JSZip) are rewritten as
// escape sequences, which is semantically identical in JS but keeps the HTML spec-clean.
const escapeControl = (s) => s.replace(/[\x00-\x08\x0e-\x1f\x7f-\x9f]/g, (c) => "\\x" + c.charCodeAt(0).toString(16).padStart(2, "0"));
const safeScript = (s) => escapeControl(s).replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");

// stylesheet
html = html.replace(/<link rel="stylesheet" href="([^"]+)"\s*\/?>/g, (_, href) => `<style>\n${read(href)}\n</style>`);

// PDF.js worker: embedded as text so it can be started as a Blob worker (or run on the main thread)
html = html.replace(
  /<meta name="pdfjs-worker-src" content="([^"]+)"\s*\/?>/,
  (_, src) => `<script type="text/plain" id="pdfjs-worker-src">${safeScript(read(src))}</script>`,
);

// classic scripts
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => `<script>\n${safeScript(read(src))}\n</script>`);

html = html.replace(
  "<!DOCTYPE html>",
  "<!DOCTYPE html>\n<!-- GENERATED by tools/make-single-file.mjs from meesho-sorter/. Edit the files there, not this one. -->",
);

fs.writeFileSync("index.html", html);
console.log("wrote index.html (" + (html.length / 1024 / 1024).toFixed(2) + " MB, self-contained)");
